"""Import the files required by CatEye into its Render PostgreSQL database."""
import argparse
import hashlib
import os
from pathlib import Path

import psycopg

from app import DATASETS, HEATMAP_NAME

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("data_dir", type=Path, help="Folder containing the four summary/profile files")
parser.add_argument("heatmap_dir", type=Path, nargs="?", default=Path("."), help="Folder generated by build_heatmaps.py")
parser.add_argument("--event-dir", type=Path, help="Optional Openplay_Event folder containing source Parquet files")
parser.add_argument("--asset-only", choices=sorted(DATASETS), help="Upload or update one named asset without requiring Heatmap files")
args = parser.parse_args()
summary = [args.data_dir / args.asset_only] if args.asset_only else [args.data_dir / name for name in sorted(DATASETS)]
heatmaps = [] if args.asset_only else sorted(path for path in args.heatmap_dir.glob("*.json.gz") if HEATMAP_NAME.fullmatch(path.name))
if not args.asset_only and len(heatmaps) != 60:
    parser.error("Expected 60 Big Five heatmap files")
if any(not path.is_file() or path.stat().st_size == 0 for path in summary + heatmaps):
    parser.error("A required data file is missing or empty")
event_files = sorted(args.event_dir.glob("*.parquet")) if args.event_dir and not args.asset_only else []
if args.event_dir and (not event_files or any(path.stat().st_size == 0 for path in event_files)):
    parser.error("The event directory must contain non-empty Parquet files")

try:
    with psycopg.connect(os.environ["DATABASE_URL"], connect_timeout=12, autocommit=True) as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS cateye_assets (
                name text PRIMARY KEY,
                size_bytes integer NOT NULL,
                sha256 text NOT NULL,
                content bytea NOT NULL
            )
        """)
        if event_files:
            db.execute("""
                CREATE TABLE IF NOT EXISTS openplay_event_files (
                    name text PRIMARY KEY,
                    size_bytes integer NOT NULL,
                    sha256 text NOT NULL,
                    content bytea NOT NULL
                )
            """)
        for path in summary + heatmaps:
            content = path.read_bytes()
            sha = hashlib.sha256(content).hexdigest()
            current = db.execute(
                "SELECT sha256, octet_length(content) FROM cateye_assets WHERE name = %s",
                (path.name,),
            ).fetchone()
            if current == (sha, len(content)):
                print(f"Already present: {path.name}", flush=True)
                continue
            db.execute("""
                INSERT INTO cateye_assets (name, size_bytes, sha256, content)
                VALUES (%s, %s, %s, %b)
                ON CONFLICT (name) DO UPDATE SET size_bytes = EXCLUDED.size_bytes,
                  sha256 = EXCLUDED.sha256, content = EXCLUDED.content
            """, (path.name, len(content), sha, content))
            print(f"Uploaded {path.name}: {len(content):,} bytes", flush=True)
        expected = [path.name for path in summary + heatmaps]
        count, size = db.execute(
            "SELECT count(*), sum(octet_length(content)) FROM cateye_assets WHERE name = ANY(%s)",
            (expected,),
        ).fetchone()
        if count != len(expected) or size != sum(path.stat().st_size for path in summary + heatmaps):
            raise SystemExit("Database file count or size verification failed.")
        print(f"Verified {count} files and {size:,} bytes in PostgreSQL.")
        for path in event_files:
            content = path.read_bytes()
            sha = hashlib.sha256(content).hexdigest()
            current = db.execute(
                "SELECT sha256, octet_length(content) FROM openplay_event_files WHERE name = %s",
                (path.name,),
            ).fetchone()
            if current == (sha, len(content)):
                print(f"Already present: {path.name}", flush=True)
                continue
            db.execute("""
                INSERT INTO openplay_event_files (name, size_bytes, sha256, content)
                VALUES (%s, %s, %s, %b)
                ON CONFLICT (name) DO UPDATE SET size_bytes = EXCLUDED.size_bytes,
                  sha256 = EXCLUDED.sha256, content = EXCLUDED.content
            """, (path.name, len(content), sha, content))
            print(f"Uploaded {path.name}: {len(content):,} bytes", flush=True)
        if event_files:
            event_names = [path.name for path in event_files]
            event_count, event_size = db.execute(
                "SELECT count(*), sum(octet_length(content)) FROM openplay_event_files WHERE name = ANY(%s)",
                (event_names,),
            ).fetchone()
            if event_count != len(event_files) or event_size != sum(path.stat().st_size for path in event_files):
                raise SystemExit("Openplay event file count or size verification failed.")
            print(f"Verified {event_count} Openplay Event Parquet files and {event_size:,} bytes in PostgreSQL.")
except KeyError:
    raise SystemExit("Set DATABASE_URL in the local environment first.") from None
except psycopg.Error as exc:
    print(f"PostgreSQL import failed ({type(exc).__name__}, SQLSTATE {exc.sqlstate or 'n/a'}).")
    raise SystemExit(1) from None
